/**
 * Reverse-lookup index built from English strings in DICTIONARY
 * for instant 0ms translation of any text node in the DOM.
 */
const REVERSE_DICT = new Map<string, Record<string, string>>();

// Populate the reverse dictionary
for (const entry of Object.values(DICTIONARY)) {
  const eng = entry["eng_Latn"];
  if (eng) {
    REVERSE_DICT.set(eng.toLowerCase().trim(), entry);
  }
}

/**
 * Fast direct lookup: given an English phrase, return its translation in targetLang if available.
 */
export function lookupDictionaryTranslation(englishText: string, targetLang: string): string | null {
  if (targetLang === "eng_Latn" || !englishText) return englishText;

  const trimmed = englishText.trim();
  const normalized = trimmed.toLowerCase();

  // Helper to extract value from dictionary entry
  const getVal = (entry: Record<string, string>) => {
    return entry[targetLang] || entry["hin_Deva"] || entry["eng_Latn"] || null;
  };

  // 1. Direct exact lookup
  let match = REVERSE_DICT.get(normalized);
  if (match) {
    const val = getVal(match);
    if (val) return val;
  }

  // 2. Strip surrounding decorative symbols, brackets, or arrows: ›, ‹, →, ←, ↗, ↘, +, •
  const symbolRegex = /^([+•›‹→←↗↘\s\-*~]*)(.*?)([+•›‹→←↗↘\s\-*~]*)$/;
  const symbolMatch = trimmed.match(symbolRegex);
  if (symbolMatch && (symbolMatch[1] || symbolMatch[3])) {
    const prefix = symbolMatch[1];
    const core = symbolMatch[2].trim();
    const suffix = symbolMatch[3];
    if (core && core.toLowerCase() !== normalized) {
      const coreTranslated = lookupDictionaryTranslation(core, targetLang);
      if (coreTranslated) {
        return prefix + coreTranslated + suffix;
      }
    }
  }

  // 3. Strip trailing punctuation: . : , ; ! ?
  const punctStripped = normalized.replace(/[.:,!?;]+$/, "").trim();
  if (punctStripped !== normalized) {
    match = REVERSE_DICT.get(punctStripped);
    if (match) {
      const val = getVal(match);
      if (val) {
        const trailingPunct = trimmed.slice(punctStripped.length);
        return val + trailingPunct;
      }
    }
  }

  // 4. Pattern matching for dynamic numbers and parameterized labels
  // e.g. "66 years" -> "66 वर्ष"
  const yearsMatch = trimmed.match(/^(\d+)\s+years?$/i);
  if (yearsMatch) {
    const suffix = targetLang === "hin_Deva" ? "वर्ष" : targetLang === "mar_Deva" ? "वर्षे" : "years";
    return `${yearsMatch[1]} ${suffix}`;
  }

  // e.g. "5 Years (60 mo)" -> "5 वर्ष (60 माह)"
  const tenureMatch = trimmed.match(/^(\d+)\s+Years?\s*\((\d+)\s*mo\)$/i);
  if (tenureMatch) {
    const yStr = targetLang === "hin_Deva" ? "वर्ष" : targetLang === "mar_Deva" ? "वर्षे" : "Years";
    const mStr = targetLang === "hin_Deva" ? "माह" : targetLang === "mar_Deva" ? "महिने" : "mo";
    return `${tenureMatch[1]} ${yStr} (${tenureMatch[2]} ${mStr})`;
  }

  // e.g. "1 Active Goals"
  const goalsMatch = trimmed.match(/^(\d+)\s+Active Goals?$/i);
  if (goalsMatch) {
    const text = targetLang === "hin_Deva" ? "सक्रिय लक्ष्य" : targetLang === "mar_Deva" ? "सक्रिय उद्दिष्टे" : "Active Goals";
    return `${goalsMatch[1]} ${text}`;
  }

  // e.g. "1 recorded assets"
  const assetsMatch = trimmed.match(/^(\d+)\s+recorded assets?$/i);
  if (assetsMatch) {
    const text = targetLang === "hin_Deva" ? "दर्ज परिसंपत्तियां" : targetLang === "mar_Deva" ? "नोंदवलेली मालमत्ता" : "recorded assets";
    return `${assetsMatch[1]} ${text}`;
  }

  // e.g. "1 recorded liabilities"
  const liabMatch = trimmed.match(/^(\d+)\s+recorded liabilities?$/i);
  if (liabMatch) {
    const text = targetLang === "hin_Deva" ? "दर्ज देनदारियां" : targetLang === "mar_Deva" ? "नोंदवलेली देणी" : "recorded liabilities";
    return `${liabMatch[1]} ${text}`;
  }

  // e.g. "+ Add Milestone (1)"
  const addMilestoneMatch = trimmed.match(/^\+\s*Add Milestone\s*\((\d+)\)$/i);
  if (addMilestoneMatch) {
    const text = targetLang === "hin_Deva" ? "मील का पत्थर जोड़ें" : targetLang === "mar_Deva" ? "उद्दिष्ट जोडा" : "Add Milestone";
    return `+ ${text} (${addMilestoneMatch[1]})`;
  }

  // e.g. "Saved: ₹50,000"
  if (/^Saved:/i.test(trimmed)) {
    const prefix = targetLang === "hin_Deva" ? "बचत:" : targetLang === "mar_Deva" ? "बचत:" : "Saved:";
    return trimmed.replace(/^Saved:/i, prefix);
  }

  // e.g. "Target: ₹5,00,000"
  if (/^Target:/i.test(trimmed)) {
    const prefix = targetLang === "hin_Deva" ? "लक्ष्य:" : targetLang === "mar_Deva" ? "उद्दिष्ट:" : "Target:";
    return trimmed.replace(/^Target:/i, prefix);
  }

  // e.g. "Need ₹4,50,000"
  if (/^Need\s+/i.test(trimmed)) {
    const prefix = targetLang === "hin_Deva" ? "आवश्यकता " : targetLang === "mar_Deva" ? "गरज " : "Need ";
    return trimmed.replace(/^Need\s+/i, prefix);
  }

  // 5. Compound prefix: e.g. "Delete & Do Not Click: Never input..."
  if (trimmed.includes(": ")) {
    const colonIdx = trimmed.indexOf(": ");
    const part1 = trimmed.slice(0, colonIdx).trim();
    const part2 = trimmed.slice(colonIdx + 2).trim();
    const trans1 = lookupDictionaryTranslation(part1, targetLang);
    const trans2 = lookupDictionaryTranslation(part2, targetLang);
    if (trans1 && trans2) {
      return `${trans1}: ${trans2}`;
    }
    if (trans1 && !trans2) {
      return `${trans1}: ${part2}`;
    }
  }

  return null;
}

/**
 * Custom hook that provides the active translation dictionary for the current selected language.
 */
export function useTranslation() {
  const selectedLang = useLanguageStore((s) => s.selectedLang);
  const setLanguage = useLanguageStore((s) => s.setLanguage);
  const translateDynamic = useLanguageStore((s) => s.translate);
  const isTranslating = useLanguageStore((s) => s.isTranslating);

  const t = useCallback(
    (key: string, fallback?: string): string => {
      if (selectedLang === "eng_Latn") {
        return fallback || DICTIONARY[key]?.["eng_Latn"] || key;
      }

      const entry = DICTIONARY[key];
      if (entry) {
        if (entry[selectedLang]) {
          return entry[selectedLang];
        }
        // Fallback to Hindi if target dialect missing, else English
        if (entry["hin_Deva"]) {
          return entry["hin_Deva"];
        }
        return entry["eng_Latn"] || fallback || key;
      }

      // Check reverse dictionary if key itself is an English string
      const reverseMatch = lookupDictionaryTranslation(key, selectedLang);
      if (reverseMatch) return reverseMatch;

      return fallback || key;
    },
    [selectedLang]
  );

  return {
    t,
    currentLang: selectedLang,
    setLanguage,
    translateDynamic,
    isTranslating,
  };
}

